/** Префиксы, отсортированные по убыванию длины — специфичные раньше общих. */
const SORTED_PREFIXES = Object.keys(ISSUER_SECTOR).sort((a, b) => b.length - a.length);

/**
 * Сектор корпоративного эмитента по короткому названию бумаги.
 * Возвращает «Другое», если эмитент не найден в карте.
 */
export const sectorByShortName = (shortName: string): string => {
    const name = shortName.trim().toLowerCase();
    const prefix = SORTED_PREFIXES.find((p) => name.startsWith(p));
    return prefix ? ISSUER_SECTOR[prefix] : BOND_SECTOR_OTHER;
};
