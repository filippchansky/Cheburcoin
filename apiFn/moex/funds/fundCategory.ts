/**
 * Определяет категорию актива фонда по его названию. Эвристика по ключевым словам —
 * в бесплатном MOEX ISS готовой классификации фондов нет. Отдельные ESG/активные
 * фонды акций могут попасть в «Смешанный» — это известный компромисс (как курируемые
 * секторы у облигаций); при необходимости пополняем словарь.
 */
export const categorizeFund = (secName: string): FundCategory => {
    const name = secName.toLowerCase();
    for (const [category, keywords] of CATEGORY_RULES) {
        if (keywords.some((keyword) => name.includes(keyword))) return category;
    }
    return 'mixed';
};
